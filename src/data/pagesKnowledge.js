export function getPageSummaryByPath(pathname) {
  const cleanPath = pathname.split('?')[0].split('#')[0];
  const found = PAGES_CORPUS.find(p => p.link === cleanPath);
  if (found) return found;

  // Partial match for dynamic paths like /c/:slug or /modules/:slug
  if (cleanPath.startsWith('/c/')) {
    return {
      title: "محتوى المعرفة",
      summary: "صفحة معرفية تفاعلية تتناول مواضيع الصحة النفسية والعلاج المعرفي السلوكي.",
      link: cleanPath
    };
  }

  if (cleanPath.startsWith('/modules/')) {
    return {
      title: "وحدة معرفية متخصصة",
      summary: "تتضمن تدريبات ونماذج معرفية تفصيلية لتنمية المهارات النفسية.",
      link: cleanPath
    };
  }

  return null;
}
